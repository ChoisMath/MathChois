export const CURRICULUM_SUBJECTS: string[] = MATH_CURRICULUM_2022.map((s) => s.subject);

/** OCR 프롬프트에 주입할 교육과정 목록 텍스트(과목 → 대단원 → 소단원 + 성취기준 코드·문장). */
export function buildCurriculumPromptBlock(): string {
  const lines: string[] = [];
  for (const s of MATH_CURRICULUM_2022) {
    lines.push(`■ 과목: ${s.subject}`);
    for (const a of s.areas) {
      lines.push(`  · 대단원: ${a.majorUnit} / 소단원: ${a.minorUnits.join(', ')}`);
      for (const st of a.standards) {
        lines.push(`      ${st.code} ${st.text}`);
      }
    }
  }
  return lines.join('\n');
}
